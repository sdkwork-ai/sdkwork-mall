#!/usr/bin/env node
// Project the selected committed mini-program profile into the typed EnvConfig.
//
// Authority: APP_RUNTIME_ENV_SPEC.md §3.1. Packaged surfaces ship one build per
// lifecycle: the profile file materialized by the canonical client-env tool is the
// authority, and the canonical generator projects it. Runtime code imports the
// generated module and never parses JSON or bakes URLs into source constants.
//
// Build order (spec §3.1): materialize topology -> materialize client env
// profiles (committed, `pnpm workflow:materialize-client-env`) -> validate the
// selected profile -> generate EnvConfig -> compile/package.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const specsRoot = path.resolve(appRoot, "..", "..", "..", "sdkwork-specs");
const appId = "sdkwork-mall-mini-program";

const args = process.argv.slice(2);
function argValue(name) {
  const index = args.indexOf(name);
  return index >= 0 ? String(args[index + 1] ?? "").trim() : "";
}

const deploymentProfile = argValue("--deployment-profile") || "cloud";
const environment = argValue("--environment") || "development";
const profile = argValue("--profile") || `${deploymentProfile}.${environment}`;
if (!/^(?:standalone|cloud)\.(?:development|test|staging|demo|production)$/u.test(profile)) {
  console.error(`[mall-mp] invalid profile "${profile}" (expected <standalone|cloud>.<environment>)`);
  process.exit(1);
}

const profilePath = path.join(appRoot, "config", "mini-program", `runtime-env.${profile}.json`);
if (!existsSync(profilePath)) {
  console.error(
    `[mall-mp] profile ${profile} is missing: ${path.relative(appRoot, profilePath)}.\n` +
      "Run `pnpm workflow:materialize-client-env` from the repository root first.",
  );
  process.exit(1);
}
const generator = path.join(specsRoot, "tools", "generate-app-env-config.mjs");
if (!existsSync(generator)) {
  console.error(`[mall-mp] canonical env generator is missing: ${generator}`);
  process.exit(1);
}

const check = args.includes("--check");
mkdirSync(path.join(appRoot, "src", "bootstrap"), { recursive: true });
execFileSync(
  process.execPath,
  [
    generator,
    "--root", appRoot,
    "--profile", profile,
    "--format", "typescript",
    "--output", "src/bootstrap/runtime-env.generated.ts",
    "--app-id", appId,
    ...(check ? ["--check"] : []),
  ],
  { stdio: "inherit" },
);

// WeChat compiles a JSON import into `require("./runtime-env.json")`/the
// module id `runtime-env.json.js`. An older compiled bundle keeps reading this
// CommonJS shim, so it must mirror the generated module exactly.
const values = JSON.parse(readFileSync(profilePath, "utf8").replace(/^\uFEFF/u, ""));
const gateway = String(values.SDKWORK_MALL_MINI_PROGRAM_PLATFORM_API_GATEWAY_HTTP_URL ?? "").replace(/\/+$/u, "");
const appApiBaseUrl = gateway ? `${gateway}/app/v3/api` : "";
const shim = {
  applicationPublicHttpUrl: String(values.SDKWORK_MALL_MINI_PROGRAM_APPLICATION_PUBLIC_HTTP_URL ?? ""),
  commerceAppApiBaseUrl: appApiBaseUrl,
  deploymentProfile: String(values.SDKWORK_DEPLOYMENT_PROFILE ?? ""),
  environment: String(values.SDKWORK_ENVIRONMENT ?? ""),
  platformApiGatewayHttpUrl: gateway,
  profileId: String(values.SDKWORK_PROFILE_ID ?? ""),
  runtimeTarget: String(values.SDKWORK_RUNTIME_TARGET ?? ""),
};
const shimPath = path.join(appRoot, "src", "runtime-env.json.js");
const shimContent = `/**
 * Compatibility shim; generated by scripts/build-runtime.mjs.
 * Mirrors the canonical EnvConfig projection for the module id
 * "runtime-env.json.js" that the WeChat compiler derives from a JSON import.
 */
module.exports = ${JSON.stringify(shim, null, 2)};
`;
if (check) {
  const actual = existsSync(shimPath) ? readFileSync(shimPath, "utf8") : "";
  if (actual !== shimContent) {
    console.error(
      `[mall-mp] ${path.relative(appRoot, shimPath)} is stale for ${profile}; run the build without --check.`,
    );
    process.exit(1);
  }
  console.log(`[mall-mp] EnvConfig projection is current for ${profile} (app id ${appId})`);
} else {
  writeFileSync(shimPath, shimContent);
  console.log(`[mall-mp] EnvConfig projected for ${profile} (app id ${appId})`);
}
