#!/usr/bin/env node
// Materialize the mini-program runtime bundle (runtime-env injection target).
//
// The WeChat compiler cannot resolve JSON modules, so the environment is
// materialized as a committed TypeScript module
// (`src/bootstrap/runtime-env.generated.ts`). The default file holds the
// development values; this script rewrites it for another deployment.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const deploymentProfile = process.argv.includes("--deployment-profile")
  ? process.argv[process.argv.indexOf("--deployment-profile") + 1]
  : "standalone";
const environment = process.argv.includes("--environment")
  ? process.argv[process.argv.indexOf("--environment") + 1]
  : "development";

const manifest = JSON.parse(readFileSync(path.join(appRoot, "agent.app.config.json"), "utf8"));
const envConfig = manifest.environments?.[environment];
if (!envConfig) {
  console.error(`[mall-mp] unknown environment: ${environment}`);
  process.exit(1);
}

const commerceAppApiBaseUrl = `${envConfig.accessUrl.replace(/\/apps\/.*$/u, "")}/app/v3/api`;
const header = `/**
 * Materialized runtime environment for the mini program.
 *
 * GENERATED by \`scripts/build-runtime.mjs\` — do not edit by hand. Regenerate with
 * \`pnpm build:runtime --environment <name> --deployment-profile <name>\`.
 *
 * A TypeScript module on purpose: a JSON import compiles to
 * \`require("./runtime-env.json")\`, which the mini-program module system cannot
 * resolve ("module 'runtime-env.json.js' is not defined").
 */
export interface SdkworkMallMpRuntimeEnvDocument {
  readonly commerceAppApiBaseUrl: string;
  readonly deploymentProfile: string;
  readonly environment: string;
}

/** Values injected at build time; \`readRuntimeEnv\` merges them with the channel. */
export const RUNTIME_ENV: SdkworkMallMpRuntimeEnvDocument = {
  commerceAppApiBaseUrl: ${JSON.stringify(commerceAppApiBaseUrl)},
  deploymentProfile: ${JSON.stringify(deploymentProfile)},
  environment: ${JSON.stringify(environment)},
};
`;

mkdirSync(path.join(appRoot, "src", "bootstrap"), { recursive: true });
writeFileSync(
  path.join(appRoot, "src", "bootstrap", "runtime-env.generated.ts"),
  header,
);
console.log(
  `[mall-mp] materialized src/bootstrap/runtime-env.generated.ts (${deploymentProfile}.${environment})`,
);
